  function applyLegalEN(data) {
    document.title = data.title;

    var h1 = document.querySelector('.page-header h1');
    if (h1) h1.textContent = data.heading;

    var dateLine = document.querySelector('.page-header p');
    if (dateLine) dateLine.textContent = data.date;

    var content = document.querySelector('.legal-content');
    if (content) content.innerHTML = data.content;

    /* Footer copy */
    var copy = document.querySelector('.footer-copy');
    if (copy) copy.textContent = '© 2026 Avtonomka. All rights reserved.';

    /* Footer legal links */
    var legalLinks = document.querySelectorAll('.footer-legal a');
    if (legalLinks[0]) legalLinks[0].textContent = 'Privacy Policy';
    if (legalLinks[1]) legalLinks[1].textContent = 'Terms of Use';

    /* Footer nav links */
    var footerNavLinks = document.querySelectorAll('.footer-links a');
    var footerNavMap = ['Home', 'Catalog', 'News', 'Articles', 'Telegram'];
    footerNavLinks.forEach(function(a, i) {
      if (footerNavMap[i] && !a.href.includes('t.me')) {
        a.textContent = footerNavMap[i];
      }
    });

    /* Header nav */
    var navLinks = document.querySelectorAll('.main-nav a');
    var navMap = { 'index.html': 'Home', 'catalog.html': 'Catalog', 'articles.html': 'Articles' };
    navLinks.forEach(function(a) {
      var href = a.getAttribute('href') || '';
      var key = href.split('/').pop();
      if (navMap[key]) a.textContent = navMap[key];
    });

    /* Header buttons */
    var partnerBtn = document.querySelector('.btn-partner');
    if (partnerBtn) partnerBtn.textContent = 'Become a Partner';
    var tgBtn = document.querySelector('.btn-tg.btn-sm');
    if (tgBtn) tgBtn.textContent = '✈ Message Us';

    /* Footer location */
    var loc = document.querySelector('.footer-contacts span');
    if (loc) loc.textContent = '📍 Odesa, Ukraine';
  }

